"""Refresh the SI throughput numbers from figures/throughput/paper_results.py without touching the enrichment
results: rewrites si_summary.json (aligns/s per SI mode), si_throughput_table.tex and
si_throughput_sources.json.

    python refresh_throughput.py               # all three files
    python refresh_throughput.py --pair-only   # si_summary.json only (needs no CPU screen cells)
"""
import json
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'throughput'))
import paper_results as source


def render(summary, require_cpu=True):
    sets = {'pairwise': source.pairwise(), 'gpu_screen': source.si_screen()}
    if require_cpu:
        sets['cpu_screen'] = source.si_cpu()
        sets['cpu_pairwise'] = source.si_cpu_pairwise()
    rows = {key: {c['mode']: c for c in values} for key, values in sets.items()}
    for mode in source.ADDITIONAL:
        summary['modes'][mode]['aligns_per_sec'] = rows['pairwise'][mode]['aligns_per_sec']
    summary['speed_n_pairs'] = 100_000
    (HERE/'si_summary.json').write_text(json.dumps(summary, indent=2)+'\n')
    from aggregate import _plot
    _plot(summary, None, None)
    # --pair-only stops after the GPU pairwise summary and plot.
    if not require_cpu:
        return
    tex=['% Generated by refresh_throughput.py; rates are conformer pairs per second.',
         r'\begin{tabular}{lrrrr}', r'\toprule',
         r' & \multicolumn{2}{c}{CPU (single core)} & \multicolumn{2}{c}{GPU} \\',
         r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}',
         r'Scoring mode & Screen & Pairwise & Screen & Pairwise \\',
         r' & $N=10^{3}$ & $N=10^{3}$ & $N=10^{5}$ & $N=10^{5}$ \\',r'\midrule']
    for mode in source.ALL:
        cells=[]
        for key in ('cpu_screen','cpu_pairwise','gpu_screen','pairwise'):
            c=rows[key].get(mode)
            cells.append(f"{c['aligns_per_sec']:,.1f}" if c and key.startswith('cpu_') else
                         f"{c['aligns_per_sec']:,.0f}" if c else '--')
        tex.append(r'\texttt{'+mode.replace('_',r'\_')+'} & '+' & '.join(cells)+r' \\')
    tex += [r'\bottomrule',r'\end{tabular}']
    (HERE/'si_throughput_table.tex').write_text('\n'.join(tex)+'\n')
    (HERE/'si_throughput_sources.json').write_text(json.dumps({k:[{f:c[f] for f in ('task_id','tool','mode','size','aligns_per_sec','compute_seconds')} for c in v] for k,v in sets.items()},indent=2)+'\n')


if __name__=='__main__':
    render(json.loads((HERE/'si_summary.json').read_text()), '--pair-only' not in sys.argv)
